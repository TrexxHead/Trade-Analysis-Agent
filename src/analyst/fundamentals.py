"""Fundamental context for Kora's breakdowns.

Sources, all real:
- Economic calendar: the free ForexFactory weekly JSON feed (impact,
  forecast, previous). It does NOT publish actual results, so Kora reads
  *expectations* (consensus vs. prior) and *event risk* (what's due and
  when), not post-release surprises.
- Cross-asset context: the same cycle's technical reads of related
  instruments (EURUSD as an inverse-USD proxy for gold/silver, gold vs.
  silver, EURUSD vs. GBPUSD).
- Trading sessions: computed from the clock.

Synthetic indices get an explicit "no fundamentals" note - they're
generated by Deriv's RNG to a fixed volatility, so macro news can't move
them and pretending otherwise would be noise.
"""
from __future__ import annotations

import json
import re
import urllib.request
from datetime import datetime, timedelta, timezone

FEEDS = [
    "https://nfs.faireconomy.media/ff_calendar_thisweek.json",
    "https://nfs.faireconomy.media/ff_calendar_nextweek.json",
]

# (keyword regex, "higher reading is ... for the currency", theme)
INDICATOR_RULES = [
    (r"\b(cpi|ppi|pce|inflation|price index)\b", +1, "inflation"),
    (r"non-?farm|employment change|payrolls|adp", +1, "jobs"),
    (r"unemployment rate|jobless|unemployment claims|claimant", -1, "jobs"),
    (r"\bgdp\b", +1, "growth"),
    (r"retail sales", +1, "consumer"),
    (r"\bpmi\b|ism ", +1, "activity"),
    (r"confidence|sentiment", +1, "sentiment"),
    (r"rate decision|cash rate|bank rate|refinancing rate|funds rate|policy rate", +1, "rates"),
    (r"average (hourly )?earnings|wage", +1, "wages"),
    (r"trade balance", +1, "trade"),
]


def fetch_calendar(timeout: float = 15.0) -> list[dict]:
    events: list[dict] = []
    for url in FEEDS:
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "kora-terminal/1.0"})
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                events.extend(json.loads(resp.read().decode()))
        except Exception:
            continue  # next week's feed is often not published until the weekend
    out, seen = [], set()
    for e in events:
        try:
            t = datetime.fromisoformat(e["date"]).astimezone(timezone.utc)
        except (KeyError, ValueError):
            continue
        key = (e.get("title"), e.get("country"), t.isoformat())
        if key in seen:
            continue
        seen.add(key)
        out.append({
            "title": e.get("title", ""), "currency": e.get("country", ""), "time": t.isoformat(),
            "impact": e.get("impact", "Low"), "forecast": e.get("forecast") or "",
            "previous": e.get("previous") or "",
        })
    return sorted(out, key=lambda e: e["time"])


def _num(s: str) -> float | None:
    m = re.search(r"-?\d+(\.\d+)?", s.replace(",", ""))
    if not m:
        return None
    v = float(m.group())
    if s.strip().endswith(("K", "k")):
        v *= 1e3
    elif s.strip().endswith(("M", "m")):
        v *= 1e6
    elif s.strip().endswith(("B", "b", "T")):
        v *= 1e9
    return v


def expectation(event: dict) -> dict | None:
    """What the consensus implies for the event's currency, if forecast and
    previous are both numeric and the indicator type is known."""
    f, p = _num(event["forecast"]), _num(event["previous"])
    if f is None or p is None or f == p:
        return None
    title = event["title"].lower()
    for pattern, polarity, theme in INDICATOR_RULES:
        if re.search(pattern, title):
            lean = polarity * (1 if f > p else -1)
            return {"lean": lean, "theme": theme,
                    "text": f"{event['currency']} {event['title']}: consensus {event['forecast']} vs prior {event['previous']} "
                            f"- {'stronger' if f > p else 'weaker'} reading expected "
                            f"({'supportive' if lean > 0 else 'negative'} for {event['currency']} if it lands there)"}
    return None


def sessions(now: datetime | None = None) -> list[dict]:
    now = now or datetime.now(timezone.utc)
    defs = [("Sydney", 21, 6), ("Tokyo", 0, 9), ("London", 7, 16), ("New York", 13, 22)]
    weekend = now.weekday() == 5 or (now.weekday() == 6 and now.hour < 21) or (now.weekday() == 4 and now.hour >= 22)
    out = []
    for name, start, end in defs:
        h = now.hour + now.minute / 60
        is_open = (start <= h < end) if start < end else (h >= start or h < end)
        if weekend:
            out.append({"name": name, "state": "Closed (weekend)", "tone": "muted"})
            continue
        if is_open:
            out.append({"name": name, "state": f"Open · closes {end:02d}:00", "tone": "g"})
        else:
            hours_until = (start - h) % 24
            tone = "a" if hours_until <= 3 else "muted"
            out.append({"name": name, "state": f"Opens {start:02d}:00" if hours_until <= 12 else "Closed", "tone": tone})
    return out


def instrument_fundamentals(meta: dict, calendar: list[dict], reads_by_code: dict[str, dict],
                            now: datetime | None = None) -> dict:
    now = now or datetime.now(timezone.utc)
    ccys = meta.get("currencies") or []
    if not ccys:
        notes = ["Synthetic index - generated by Deriv's RNG at a fixed volatility. No economic data, news, "
                 "or sessions move it; this breakdown is purely technical/statistical."]
        if meta.get("spikes"):
            notes.append(f"{meta['name']} produces sudden {'upward' if meta['spikes'] == 'up' else 'downward'} spikes "
                         f"(on average ~1 per 500 ticks). Positions against the spike direction carry gap risk "
                         f"that a stop may not fully contain.")
        return {"applicable": False, "notes": notes, "events": [], "event_risk": None, "lean": 0, "lean_text": "n/a"}

    horizon = now + timedelta(hours=36)
    relevant = [e for e in calendar if e["currency"] in ccys and e["impact"] in ("High", "Medium")
                and now - timedelta(hours=2) <= datetime.fromisoformat(e["time"]) <= horizon]
    upcoming = [e for e in relevant if datetime.fromisoformat(e["time"]) >= now]
    event_risk = None
    for e in upcoming:
        mins = (datetime.fromisoformat(e["time"]) - now).total_seconds() / 60
        if e["impact"] == "High" and mins <= 120:
            event_risk = {"title": e["title"], "currency": e["currency"], "minutes": round(mins),
                          "text": f"High-impact {e['currency']} {e['title']} in {int(mins // 60)}h {int(mins % 60):02d}m "
                                  f"- expect a volatility spike; avoid fresh entries ±15 min around it."}
            break

    # Net consensus lean for the instrument: how the expected readings tilt each currency,
    # translated to the instrument (base positive / quote negative; gold & silver trade inverse to USD).
    lean, lean_notes = 0.0, []
    for e in upcoming:
        x = expectation(e)
        if not x:
            continue
        w = 1.0 if e["impact"] == "High" else 0.5
        effect = x["lean"] * w
        if meta["code"] in ("XAUUSD", "XAGUSD"):
            effect = -effect  # USD strength is a headwind for metals
        elif len(ccys) == 2 and e["currency"] == ccys[1]:
            effect = -effect  # quote currency strength pushes the pair down
        lean += effect
        lean_notes.append(x["text"])

    notes = []
    proxy = meta.get("usd_proxy")
    if proxy and reads_by_code.get(proxy):
        d = (reads_by_code[proxy].get("H4") or {}).get("direction")
        if d in ("up", "down"):
            usd = "weakening" if d == "up" else "strengthening"
            notes.append(f"USD proxy ({proxy}) is trending {d} on H4 → dollar {usd}, which is "
                         f"{'supportive' if d == 'up' else 'a headwind'} for {meta['name'].lower()}.")
            lean += 0.5 if d == "up" else -0.5
    peer = meta.get("peer")
    if peer and reads_by_code.get(peer):
        mine = (reads_by_code.get(meta["code"], {}).get("H4") or {}).get("direction")
        theirs = (reads_by_code[peer].get("H4") or {}).get("direction")
        if mine in ("up", "down") and theirs in ("up", "down"):
            notes.append(f"{peer} is {'confirming' if mine == theirs else 'diverging from'} the move "
                         f"(H4 {theirs} vs {meta['code']} {mine}).")

    lean_text = "neutral" if abs(lean) < 0.5 else ("supportive (bullish tilt)" if lean > 0 else "headwind (bearish tilt)")
    return {"applicable": True, "notes": notes + lean_notes[:4], "events": relevant[:8], "event_risk": event_risk,
            "lean": round(lean, 2), "lean_text": lean_text}
